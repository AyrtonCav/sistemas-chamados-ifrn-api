-- Tabela independente que serve de referência para usuários e categorias.
CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    sigla VARCHAR(255) NOT NULL UNIQUE
);

-- Usuários podem, opcionalmente, estar associados a um setor.
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    matricula INTEGER NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL,
    setor_id BIGINT,
    CONSTRAINT fk_usuario_setor
        FOREIGN KEY (setor_id) REFERENCES setor (id)
);

-- Cada categoria pertence obrigatoriamente a um setor.
CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL UNIQUE,
    descricao VARCHAR(255) NOT NULL,
    setor_id BIGINT NOT NULL,
    CONSTRAINT fk_categoria_setor
        FOREIGN KEY (setor_id) REFERENCES setor (id)
);

-- Um chamado possui solicitante e categoria obrigatórios, mas técnico opcional.
CREATE TABLE chamado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    local VARCHAR(255) NOT NULL,
    prioridade VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    data_abertura TIMESTAMP NOT NULL,
    data_fechamento TIMESTAMP,
    solucao VARCHAR(1000),
    solicitante_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    tecnico_id BIGINT,
    CONSTRAINT fk_chamado_solicitante
        FOREIGN KEY (solicitante_id) REFERENCES usuario (id),
    CONSTRAINT fk_chamado_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_chamado_tecnico
        FOREIGN KEY (tecnico_id) REFERENCES usuario (id)
);

-- Interações pertencem a um chamado e podem identificar o usuário autor.
CREATE TABLE interacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(1000) NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    chamado_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_interacao_chamado
        FOREIGN KEY (chamado_id) REFERENCES chamado (id),
    CONSTRAINT fk_interacao_autor
        FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
